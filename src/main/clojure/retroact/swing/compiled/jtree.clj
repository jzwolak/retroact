(defn- create-hierarchy-listener [tree-model]
  (proxy [Object HierarchyListener] []
    (hierarchyChanged [hierarchy-event]
      (when-not (zero? (bit-and HierarchyEvent/PARENT_CHANGED (.getChangeFlags hierarchy-event)))
