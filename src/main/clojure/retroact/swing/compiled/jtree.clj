    (dissoc state :tree-scroll-path)))

(defn- update-tree
  [state]
  (->
    (let [data (:data state)
          tree-model-fn (:tree-model-fn state)
          [tree-root tree] (tree-model-fn (:tree-root state) data)]
      (assoc state :tree tree
                   :tree-root tree-root))
    (update-tree-selection)
    (update-tree-scroll-path)))

